# ── Categories to hide in study set elevation views ─────────────────────────
# These Revit annotation category names get visibility turned off
HIDE_CATEGORIES = [
    "Door Tags",
    "Window Tags",
    "Dimensions",
    "Detail Items",
    "Section Boxes",
    "Callout Heads",
    "Callout Boundaries",
    "Elevation Tags",
    "Level Tags",
    "Grid Heads",
    "Keynote Tags",
    "Material Tags",
    "Generic Annotation",
]

# ── Sheet numbers that belong in a study set ─────────────────────────────────
STUDY_SHEET_NUMBERS = {"A100", "A100.1", "A100.2.1", "A100.2.2", "A101.1", "A101.2", "A105", "A106"}


def run(state: dict = None):
    """Main entry point — generate the study set."""
    if state is None:
        state = load_state()

    doc_title = state.get("summary", {}).get("title", "Unknown Project")
    is_two_story = state.get("summary", {}).get("is_two_story", False)

    print(f"\n📐 Study Set Generator — {doc_title}")
    print("=" * 55)

    # Step 1: Find existing sheets and views
    print("\n── Step 1: Scanning sheets & views ──")
    sheets = _get_sheets()
    views  = _get_views()

    sheet_map = {s.get("number", s.get("sheet_number", "")): s for s in sheets}
    view_map  = {v.get("name", ""): v for v in views}

    _report_existing(sheet_map, is_two_story)

    # Step 2: Handle 3D views (A100.2.1 / A100.2.2)
    print("\n── Step 2: 3D Views ──")
    needs_3d_input = _handle_3d_views(sheet_map, view_map)

    # Step 3: Create/update study set elevation views (tags hidden)
    print("\n── Step 3: Study Set Elevation Views ──")
    study_elev_views = _create_study_elevations(view_map, sheet_map)

    # Step 4: Build study set sheet set
    print("\n── Step 4: Building Study Set Sheets ──")
    _build_study_sheets(sheet_map, view_map, study_elev_views, is_two_story)

    # Step 5: Generate A111 upsell page
    print("\n── Step 5: A111 Upsell Page ──")
    a111_path = _handle_a111(doc_title, sheet_map)

    # Step 6: Export PDF
    print("\n── Step 6: Export PDF ──")
    if needs_3d_input:
        print("⏸  Pausing before export — 3D views need positioning.")
        print("   In Revit: adjust the 3D view camera angles on sheets A100.2.1 and A100.2.2,")
        print("   then run:  python3 run.py study-set-export")
        _save_export_state(doc_title, a111_path)
    else:
        export_study_set(doc_title, a111_path)


def export_study_set(doc_title: str = None, a111_path: str = None):
    """Export the study set PDF. Can be called standalone after 3D view adjustment."""
    state = load_state()
    if doc_title is None:
        doc_title = state.get("summary", {}).get("title", "Unknown Project")
    if a111_path is None:
        a111_path = _load_export_state().get("a111_path")

    print(f"\n📤 Exporting study set — {doc_title}")
    revit_pdf_path = _export_revit_pdf(doc_title)

    if revit_pdf_path and a111_path:
        final_path = _merge_pdfs(revit_pdf_path, a111_path, doc_title)
        print(f"\n✅ Study set ready: {final_path}")
    elif revit_pdf_path:
        print(f"\n✅ Study set exported (no A111 merge): {revit_pdf_path}")
    else:
        print("\n⚠️  Revit PDF export not available via bridge — export manually:")
        print("   File → Print → Sheet Set: STUDY SET → PDF")
        if a111_path:
            print(f"   Then merge with: {a111_path}")


