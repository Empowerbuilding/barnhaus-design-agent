"""
study_set.py — Generates a Barnhaus Study Set from an open Revit model.

Study set = 9 sheets:
  A100    Cover Sheet (renderings)
  A100.1  Cover Sheet Interior
  A100.2.1  3D Views (wireframe)
  A100.2.2  3D Cuts (section box)
  A101.1  Floor Plan F1
  A101.2  Floor Plan F2 (if 2-story)
  A105    Elevations - Sides  (tags/dims hidden)
  A106    Elevations - Front/Back  (tags/dims hidden)
  A111    Upgrade upsell page (generated by Python)

Usage:
    python3 run.py study-set
"""

import os
